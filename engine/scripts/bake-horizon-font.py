"""Bake the bundled OFL Noto Sans face for the native controls overlay (Pillow required)."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1] / "switch-port/fonts"
POINTS = list(range(32, 127)) + sorted(set(map(ord, "áéíóúüñÁÉÍÓÚÜÑ¿¡·")))
SIZE, CELL, WIDTH = 36, 50, 512


def pack(data):
    """Pack runs of equal coverage, keeping antialiased edges as literal spans."""
    out = bytearray()
    i = 0
    while i < len(data):
        run = 1
        while run < 128 and i + run < len(data) and data[i + run] == data[i]:
            run += 1
        if run >= 3:
            out.extend((0x80 | (run - 1), data[i]))
            i += run
        else:
            end = i + run
            while end < min(i + 128, len(data)) and not (
                end + 2 < len(data) and data[end] == data[end + 1] == data[end + 2]
            ):
                end += 1
            out.append(end - i - 1)
            out.extend(data[i:end])
            i = end
    return out


font = ImageFont.truetype(str(ROOT / "NotoSans.ttf"), SIZE)
height = ((len(POINTS) + 9) // 10) * CELL
atlas = Image.new("L", (WIDTH, height))
draw = ImageDraw.Draw(atlas)
glyphs = []
for i, code in enumerate(POINTS):
    char = chr(code)
    l, t, r, b = font.getbbox(char, anchor="ls")
    x, y = i % 10 * CELL + 2, i // 10 * CELL + 2
    assert r - l <= CELL - 4 and b - t <= CELL - 4
    draw.text((x - l, y - t), char, font=font, anchor="ls", fill=255)
    glyphs.append(f"    [{code}] = {{{x},{y},{r-l},{b-t},{l},{t},{font.getlength(char):.4f}f}},")
packed = pack(atlas.tobytes())
lines = [f"/* Generated by scripts/bake-horizon-font.py. Noto Sans, SIL OFL 1.1. */",
         f"enum {{ FONT_WIDTH = {WIDTH}, FONT_HEIGHT = {height}, FONT_SIZE = {SIZE} }};",
         "static const NxGlyph glyphs[256] = {", *glyphs, "};", "static const uint8_t font_pixels[] = {"]
for i in range(0, len(packed), 24):
    lines.append("    " + ",".join(f"0x{b:02x}" for b in packed[i:i+24]) + ",")
lines.extend(["};", ""])
(ROOT / "noto-atlas.inc").write_text("\n".join(lines), encoding="utf-8", newline="\n")
