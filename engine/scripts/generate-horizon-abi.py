"""Generate paired C/Rust fact expressions; --check verifies checked-in probes."""
from pathlib import Path
import argparse,json
parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
root=Path(__file__).resolve().parents[1]
for name in ['abi-probe','network-abi-probe']:
    p=root/'switch-port'/name
    facts=json.loads((p/'facts.json').read_text())
    headers=['stdint.h','stddef.h','sys/types.h','sys/stat.h','dirent.h','pthread.h','time.h','fcntl.h','errno.h','limits.h','unistd.h'] if name=='abi-probe' else ['stdint.h','stddef.h','sys/socket.h','netinet/in.h','netdb.h','poll.h','sys/time.h','sys/_iovec.h','netinet/tcp.h']
    c='/* SPDX-License-Identifier: MIT. Generated by generate-horizon-abi.py. */\n#define _GNU_SOURCE 1\n'+''.join('#include <'+h+'>\n' for h in headers)+f'const uint64_t NX_C_ABI[{len(facts)}]={{\n'+',\n'.join('    '+f['c'] for f in facts)+'\n};\n'
    rust='//! Generated by generate-horizon-abi.py; independent compiler facts.\n#![no_std]\nuse core::mem::{size_of,align_of,offset_of};\n#[no_mangle]\npub static NX_RUST_ABI:[u64;'+str(len(facts))+']=[\n'+',\n'.join('    ('+f['rust']+') as u64' for f in facts)+'\n];\n'
    for path,text in [(p/'native.c',c),(p/'src/lib.rs',rust)]:
        if args.check:
            if path.read_text()!=text:raise SystemExit('Out of date: '+str(path))
        else:path.write_text(text)

